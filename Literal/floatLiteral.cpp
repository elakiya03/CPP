#include <iostream>
using namespace std;

int main()
{

    // float literal (Suffix: f or F)
    float f = 3.14f;

    // Default - double literal (Suffix: d or D)
    double d = 3.14;

    // long double literal (Suffix: l or L)
    long double ld = 3.14L;

    // Scientific notation
    long double sld = 1.22e11;

    cout << f << endl;
    cout << d << endl;
    cout << ld << endl;
    cout << sld;

    return 0;
}
